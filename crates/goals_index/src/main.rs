//! `goals_index`: generate goal data and pages for the blog, and check that
//! every post's `extra.goals` entries refer to real project goals.
//!
//! Usage: `cargo run -p goals_index -- <path to rust-lang/goals checkout>`
//!
//! Writes (all gitignored, regenerated on every build):
//! - `data/goals.json`: every goal, plus the alias table used by templates.
//! - `content/goals/_index.md` and `content/goals/<slug>.md`: one page per goal
//!   that at least one post refers to, with redirects from its other slugs.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use goals_index::{read_goal_docs, Goal, GoalsIndex};
use serde::Serialize;

/// A goal as referenced from one post.
#[derive(Serialize)]
struct PostGoal {
    issue: u64,
    slug: String,
    title: String,
}

fn main() -> ExitCode {
    let Some(goals_repo) = std::env::args().nth(1).map(PathBuf::from) else {
        eprintln!("usage: goals_index <path to rust-lang/goals checkout>");
        return ExitCode::FAILURE;
    };
    let site = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    match run(&goals_repo, &site) {
        Ok(true) => ExitCode::SUCCESS,
        Ok(false) => ExitCode::FAILURE,
        Err(e) => {
            eprintln!("error: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run(goals_repo: &Path, site: &Path) -> Result<bool, Box<dyn std::error::Error>> {
    let docs = read_goal_docs(goals_repo)?;
    let index = GoalsIndex::build(&docs);
    eprintln!(
        "read {} goal documents for {} tracking issues",
        docs.len(),
        index.goals.len()
    );

    // Check every post and collect the goals that have posts.
    let mut ok = true;
    let content = site.join("content");
    let mut used: BTreeMap<u64, (&Goal, Vec<String>)> = BTreeMap::new();
    // Post path (relative to content/, as Zola's `page.relative_path`) to the
    // goals it refers to, for templates.
    let mut post_goals: BTreeMap<String, Vec<PostGoal>> = BTreeMap::new();
    for post in posts(&content)? {
        let rel = post.strip_prefix(&content)?.to_string_lossy().replace('\\', "/");
        for reference in goal_refs(&post)? {
            match index.resolve(&reference) {
                Ok(goal) => {
                    let entry = used.entry(goal.issue).or_insert((goal, vec![]));
                    if !entry.1.contains(&rel) {
                        entry.1.push(rel.clone());
                        post_goals.entry(rel.clone()).or_default().push(PostGoal {
                            issue: goal.issue,
                            slug: goal.canonical_slug.clone(),
                            title: goal.title.clone(),
                        });
                    }
                }
                Err(e) => {
                    ok = false;
                    eprintln!("error: {}: {e}", post.strip_prefix(site).unwrap_or(&post).display());
                }
            }
        }
    }

    fs::create_dir_all(site.join("data"))?;
    let data = serde_json::json!({
        "goals": index.goals,
        "aliases": index.aliases,
        "ambiguous": index.ambiguous,
        "post_goals": post_goals,
    });
    fs::write(site.join("data/goals.json"), serde_json::to_string_pretty(&data)?)?;

    let goals_dir = site.join("content/goals");
    if goals_dir.exists() {
        fs::remove_dir_all(&goals_dir)?;
    }
    fs::create_dir_all(&goals_dir)?;
    fs::write(
        goals_dir.join("_index.md"),
        "+++\n# Generated by crates/goals_index; do not edit.\ntitle = \"Project goals\"\ntemplate = \"goals.html\"\npage_template = \"goal.html\"\nsort_by = \"title\"\n+++\n",
    )?;
    for (goal, posts) in used.values() {
        let aliases: Vec<String> = goal
            .periods
            .values()
            .map(|s| s.to_lowercase())
            .filter(|s| *s != goal.canonical_slug)
            .collect::<std::collections::BTreeSet<_>>()
            .into_iter()
            .map(|s| format!("goals/{s}/"))
            .collect();
        let front = format!(
            "+++\n# Generated by crates/goals_index; do not edit.\ntitle = {title}\naliases = {aliases}\n[extra]\nissue = {issue}\nlatest_period = \"{period}\"\ndoc_url = \"{doc}\"\nissue_url = \"{issue_url}\"\nposts = {posts}\n+++\n",
            title = toml::Value::String(goal.title.clone()),
            aliases = toml::Value::Array(aliases.into_iter().map(toml::Value::String).collect()),
            issue = goal.issue,
            period = goal.latest_period,
            doc = goal.doc_url,
            issue_url = goal.issue_url,
            posts = toml::Value::Array(posts.iter().cloned().map(toml::Value::String).collect()),
        );
        fs::write(goals_dir.join(format!("{}.md", goal.canonical_slug)), front)?;
    }
    eprintln!("wrote pages for {} goals with posts", used.len());
    Ok(ok)
}

/// All post files: Markdown under `content/`, except section `_index.md`
/// files and the generated `content/goals/` directory.
fn posts(content: &Path) -> std::io::Result<Vec<PathBuf>> {
    let mut out = Vec::new();
    let mut stack = vec![content.to_path_buf()];
    while let Some(dir) = stack.pop() {
        for entry in fs::read_dir(&dir)? {
            let path = entry?.path();
            if path.is_dir() {
                if path != content.join("goals") {
                    stack.push(path);
                }
            } else if path.extension().and_then(|e| e.to_str()) == Some("md")
                && path.file_name().and_then(|n| n.to_str()) != Some("_index.md")
            {
                out.push(path);
            }
        }
    }
    out.sort();
    Ok(out)
}

/// The `extra.goals` list from a post's TOML front matter.
fn goal_refs(post: &Path) -> Result<Vec<String>, Box<dyn std::error::Error>> {
    let text = fs::read_to_string(post)?;
    let Some(rest) = text.strip_prefix("+++") else {
        return Ok(vec![]);
    };
    let Some((front, _)) = rest.split_once("\n+++") else {
        return Err(format!("{}: unterminated front matter", post.display()).into());
    };
    let value: toml::Table = toml::from_str(front)?;
    let goals = value
        .get("extra")
        .and_then(|e| e.get("goals"))
        .and_then(|g| g.as_array())
        .map(|a| a.iter().filter_map(|v| v.as_str().map(String::from)).collect())
        .unwrap_or_default();
    Ok(goals)
}
